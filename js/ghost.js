    const pace = ms => packetMs(ms);
    resetFlow(); traceEl.textContent = ''; stepNo = 0;
    bubble('me', esc(text));
    const typing = bubble('bot', '<span class="gh-dots"><i></i><i></i><i></i></span>', 'typing');

    // 1. FastAPI
    setNode('user', 'done'); await packet('user', 'api', pace(520)); if (!live()) return;
