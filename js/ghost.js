  function setEdge(a, b, state){ const e = edgeEls[a + '>' + b]; if (!e) return; e.classList.remove('on', 'dim'); if (state) e.classList.add(state); }
  function resetFlow(){ Object.keys(nodeEls).forEach(k => setNode(k, null)); Object.values(edgeEls).forEach(e => e.classList.remove('on', 'dim')); svg.querySelectorAll('.chip').forEach(c => c.classList.remove('on')); svg.querySelectorAll('.gh-pk').forEach(p => p.remove()); }
  // a glowing packet travels along an edge
  function packet(a, b, ms){
    const path = edgeEls[a + '>' + b]; if (!path) return Promise.resolve();
    setEdge(a, b, 'on');
    const len = path.getTotalLength(), c = document.createElementNS(NS, 'circle');
    c.setAttribute('r', 5); c.setAttribute('class', 'gh-pk'); c.setAttribute('filter', 'url(#ghGlow)'); svg.appendChild(c);
    const t0 = G.now(), id = RUN;
    return new Promise(res => {
      const f = now => {
        if (id !== RUN){ c.remove(); return res(); }
        const k = Math.min(1, (now - t0) / ms), e = k < .5 ? 2 * k * k : 1 - Math.pow(-2 * k + 2, 2) / 2, p = path.getPointAtLength(e * len);
        c.setAttribute('cx', p.x); c.setAttribute('cy', p.y);
        if (k < 1) G.frame(f); else { c.remove(); res(); }
      };
      G.frame(f);
    });
  }

