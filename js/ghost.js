    trace('Context', `${parts.join(' + ')} ≈ ${ctxTokens} tokens`, mems.some(x => /concise/i.test(x.m.text)) ? '<small>memory applied: keep the answer concise</small>' : '', null);
    setNode('llm', 'active', 'generating');
    const outTok = tok(reply), tps = fake(24, 34);
    const genTrace = trace('Qwen3 8B', `generating · ${outTok} tokens`, '', null);
    await packet('llm', 'out', pace(420)); if (!live()) return;
    typing.classList.remove('typing'); typing.textContent = '';
    setNode('out', 'active', 'streaming');
    await stream(typing, reply, id); if (!live()) return;
    genTrace.querySelector('.h').insertAdjacentHTML('beforeend', `<em>${Math.round(outTok / tps * 1000)} ms · ~${tps} tok/s</em>`);
    setNode('llm', 'done'); setNode('out', 'done');
    // badges under the reply: what this answer used
    const badges = [r.tool && `🛠 ${r.tool}`, mems.length && `🧠 ${mems.length} memor${mems.length === 1 ? 'y' : 'ies'}`, chunks && '📄 3 chunks'].filter(Boolean);
