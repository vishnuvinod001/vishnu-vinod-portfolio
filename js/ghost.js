    trace('Memory', mems.length ? `${mems.length} relevant memor${mems.length === 1 ? 'y' : 'ies'}` : 'nothing relevant stored',
      mems.map(x => `<div class="hit"><i>${x.m.cat}</i>${esc(x.m.text)}<em>${x.s.toFixed(2)}</em></div>`).join(''), fake(2, 8));
    setNode('mem', 'done', mems.length ? String(mems.length) : '0');

    // 5. RAG retrieval (normal conversations only, when documents are relevant)
    let chunks = null;
    if (ragApplies(text, r)){
      await packet('router', 'rag', pace(480)); if (!live()) return;
      setNode('rag', 'active', 'embedding'); await wait(500); if (!live()) return;
      setNode('rag', 'active', 'FAISS'); await wait(350); if (!live()) return;
      chunks = retrieve(text);
      trace('RAG', 'nomic-embed-text → FAISS · top 3 chunks', chunks.map(c => `<div class="hit"><i>${esc(c.d)} p.${c.p}</i>${esc(c.t.length > 110 ? c.t.slice(0, 107) + '…' : c.t)}<em>${c.s.toFixed(2)}</em></div>`).join(''), fake(18, 45));
      setNode('rag', 'done', '3');
    } else {
      setNode('rag', 'skip'); setEdge('router', 'rag', 'dim');
      trace('RAG', 'skipped', `<small>${r.tool ? 'a tool handled this request' : 'not a question about an uploaded document'}</small>`, null, 'skip');
    }

    // 6–7. Context → Qwen3 8B
    const newMem = !r.tool ? extract(text) : null;
    const reply = compose(text, r, tool, mems, chunks, newMem);
    const parts = ['system prompt', 'message'];
    if (mems.length) parts.push(`${mems.length} memor${mems.length === 1 ? 'y' : 'ies'}`);
    if (tool) parts.push('tool result'); if (chunks) parts.push('3 chunks');
    const ctxTokens = 180 + tok(text) + mems.reduce((s, x) => s + tok(x.m.text), 0) + (tool ? 60 + (tool.data && tool.data.text ? tok(tool.data.text) : 20) : 0) + (chunks ? chunks.reduce((s, c) => s + tok(c.t), 0) : 0);
    const used = [tool && 'mcp', 'mem', chunks && 'rag'].filter(Boolean);
